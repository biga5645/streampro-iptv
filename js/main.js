// ===== SYNC FROM ADMIN PANEL =====
function syncFromAdmin() {
  // --- Prices ---
  try {
    const plans = JSON.parse(localStorage.getItem('streampro_prices'));
    if (plans && plans.length === 3) {
      const cards = document.querySelectorAll('.price-card');
      plans.forEach((plan, i) => {
        const card = cards[i];
        if (!card) return;

        // Amount
        const amountEl = card.querySelector('.amount');
        if (amountEl) amountEl.textContent = plan.price;

        // Name (first h3)
        const nameEl = card.querySelector('h3');
        if (nameEl) nameEl.textContent = plan.name;

        // Save badge
        let saveEl = card.querySelector('.price-save');
        if (plan.save && plan.save.trim()) {
          if (!saveEl) {
            saveEl = document.createElement('div');
            saveEl.className = 'price-save';
            card.querySelector('.price-amount').insertAdjacentElement('afterend', saveEl);
          }
          saveEl.textContent = plan.save;
          saveEl.style.display = '';
        } else if (saveEl) {
          saveEl.style.display = 'none';
        }

        // Devices line — find the li that mentions "جهاز" or "devices"
        const lisAll = card.querySelectorAll('.price-features li');
        lisAll.forEach(li => {
          if (li.textContent.includes('جهاز') || li.textContent.includes('device') || li.textContent.includes('appareil')) {
            li.textContent = `✓ ${plan.devices} جهاز في آن واحد`;
          }
        });

        // Popular badge
        const popBadge = card.querySelector('.popular-badge');
        if (plan.popular) {
          card.classList.add('popular');
          if (!popBadge) {
            const b = document.createElement('div');
            b.className = 'popular-badge';
            b.textContent = 'الأكثر طلباً';
            card.insertAdjacentElement('afterbegin', b);
          }
        } else {
          card.classList.remove('popular');
          if (popBadge) popBadge.remove();
        }
      });
    }
  } catch(e) {}

  // --- Email ---
  try {
    const email = localStorage.getItem('streampro_email');
    if (email) {
      document.querySelectorAll('a[href^="mailto:"]').forEach(a => {
        a.href = 'mailto:' + email;
        a.textContent = email;
      });
    }
  } catch(e) {}

  // --- Testimonials ---
  try {
    const testis = JSON.parse(localStorage.getItem('streampro_testimonials'));
    if (testis && testis.length) {
      const grid = document.querySelector('.testi-grid');
      if (grid) {
        function starStr(n) { return '★'.repeat(n) + '☆'.repeat(5 - n); }
        grid.innerHTML = testis.map(t => `
          <div class="testi-card fade-in visible">
            <div class="stars">${starStr(t.stars)}</div>
            <p>"${escHtmlSite(t.text)}"</p>
            <div class="testi-author">
              <div class="author-avatar">${t.name.charAt(0)}</div>
              <div>
                <strong>${escHtmlSite(t.name)}</strong>
                <span>${escHtmlSite(t.loc)}</span>
              </div>
            </div>
          </div>
        `).join('');
      }
    }
  } catch(e) {}

  // --- FAQs ---
  try {
    const faqs = JSON.parse(localStorage.getItem('streampro_faqs'));
    if (faqs && faqs.length) {
      const list = document.querySelector('.faq-list');
      if (list) {
        list.innerHTML = faqs.map(f => `
          <div class="faq-item">
            <button class="faq-q">${escHtmlSite(f.q)}</button>
            <div class="faq-a"><p>${escHtmlSite(f.a)}</p></div>
          </div>
        `).join('');
        // Re-bind accordion
        list.querySelectorAll('.faq-q').forEach(btn => {
          btn.addEventListener('click', () => {
            const item = btn.parentElement;
            const isOpen = item.classList.contains('open');
            list.querySelectorAll('.faq-item.open').forEach(i => i.classList.remove('open'));
            if (!isOpen) item.classList.add('open');
          });
        });
      }
    }
  } catch(e) {}

  // --- Contact form email target ---
  try {
    const email = localStorage.getItem('streampro_email');
    if (email) {
      const form = document.getElementById('contactForm');
      if (form) form.dataset.email = email;
    }
  } catch(e) {}
}

function escHtmlSite(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

syncFromAdmin();

// ===== CONTACT FORM — EmailJS background send =====
document.getElementById('contactForm').addEventListener('submit', async function(e) {
  e.preventDefault();

  const name   = document.getElementById('fname').value.trim();
  const email  = document.getElementById('femail').value.trim();
  if (!name || !email) return;

  const plan   = document.getElementById('fplan').value;
  const device = document.getElementById('fdevice').value;
  const msg    = document.getElementById('fmsg').value.trim();
  const dest   = localStorage.getItem('streampro_email') || 'contact@streampro.tv';
  const brand  = localStorage.getItem('streampro_brand') || 'StreamPro IPTV';

  // زر الإرسال — حالة التحميل
  const submitBtn = this.querySelector('.btn-submit');
  const origText  = submitBtn.textContent;
  submitBtn.disabled    = true;
  submitBtn.textContent = '⏳ جاري الإرسال...';

  const success = document.getElementById('formSuccess');
  success.classList.remove('show', 'error');

  // هل EmailJS مفعّل؟
  let ejsCfg = null;
  try {
    const stored = localStorage.getItem('streampro_admin');
    if (stored) {
      const db = JSON.parse(stored);
      if (db.emailjs && db.emailjs.serviceId && db.emailjs.templateId && db.emailjs.publicKey) {
        ejsCfg = db.emailjs;
      }
    }
  } catch(err) {}

  if (ejsCfg) {
    // ── الإرسال في الخلفية عبر EmailJS SDK ──
    try {
      emailjs.init(ejsCfg.publicKey);
      const res = await emailjs.send(ejsCfg.serviceId, ejsCfg.templateId, {
        to_email  : dest,
        from_name : name,
        reply_to  : email,
        plan      : plan || '—',
        device    : device || '—',
        message   : msg || '—',
        brand     : brand
      });

      if (res.status === 200) {
        showSuccess(success, '✓ تم إرسال طلبك بنجاح! سنتواصل معك قريباً.');
        this.reset();
      } else {
        showSuccess(success, '⚠️ حدث خطأ أثناء الإرسال. تواصل معنا مباشرة على ' + dest, true);
      }
    } catch(err) {
      console.warn('EmailJS error:', err);
      showSuccess(success, '⚠️ فشل الإرسال: ' + (err.text || err.message || 'خطأ غير معروف'), true);
    }
  } else {
    // ── EmailJS غير مفعّل — أظهر رسالة للزبون بدل فتح أي تطبيق ──
    showSuccess(success, '✓ تم استلام طلبك! سنتواصل معك على ' + email + ' قريباً.', false);
    this.reset();
  }

  submitBtn.disabled    = false;
  submitBtn.textContent = origText;
});

function showSuccess(el, text, isError = false) {
  el.innerHTML = `<span>${text}</span>`;
  el.classList.remove('show', 'error');
  if (isError) el.classList.add('error');
  el.classList.add('show');
  setTimeout(() => el.classList.remove('show'), 7000);
}
